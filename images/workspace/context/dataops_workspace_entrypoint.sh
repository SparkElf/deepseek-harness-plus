#!/bin/sh
set -u

SIDECARS_PID=''
MAIN_PID=''
SIDECARS_LOG='/tmp/dataops-workspace-platform-sidecars.log'
INTERNAL_TOKEN_FILE='/run/dataops-workspace/internal-token'

# A DSH session resolves its default working directory as $HOME/workspace, while the workspace
# volume is mounted at /workspace. Without this link the first session fails with
# "working-directory: directory does not exist: \"/root/workspace\"" on any deployment that starts
# DSH without the DataOps supervisor (which passes an explicit workspace root).
if [ -d /workspace ] && [ ! -e "${HOME:-/root}/workspace" ]; then
  ln -sfn /workspace "${HOME:-/root}/workspace" 2>/dev/null || true
fi

# The deployment uplink is 1492 bytes (PPPoE), and a 1500-byte container link black-holes the
# large TLS records the DSH websocket carries: the page renders while every stream stalls, which
# reads as a hung backend rather than a link problem. A container holds no CAP_NET_ADMIN, so the
# MTU this process can observe was set when the container was created -- by the host script
# `persist-mss-clamp.sh`, which also installs the FORWARD MSS clamp. Attempt the change anyway
# (a deployment that grants NET_ADMIN gets it applied here) and report the observed value, so a
# missing host step is visible in the container log instead of only in a stalled session.
report_link_mtu() {
  expected=1492
  iface=eth0
  observed="$(cat "/sys/class/net/$iface/mtu" 2>/dev/null || echo unknown)"
  if [ "$observed" != "$expected" ]; then
    if command -v ip >/dev/null 2>&1; then
      ip link set dev "$iface" mtu "$expected" 2>/dev/null || true
      observed="$(cat "/sys/class/net/$iface/mtu" 2>/dev/null || echo unknown)"
    fi
  fi
  if [ "$observed" = "$expected" ]; then
    echo "[dataops-workspace-entrypoint] $iface mtu=$observed"
  else
    echo "[dataops-workspace-entrypoint] $iface mtu=$observed (expected $expected): the host must set the link MTU and the FORWARD MSS clamp; run infra/docker-workspace/persist-mss-clamp.sh on the host" >&2
  fi
}

report_link_mtu

stop_child() {
  pid="$1"
  if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
    kill "$pid" 2>/dev/null || true
    wait "$pid" 2>/dev/null || true
  fi
}

shutdown() {
  stop_child "$MAIN_PID"
  stop_child "$SIDECARS_PID"
  exit 0
}

trap shutdown TERM INT

# Temporary admin tunnel (docs/admin-workspace-ops-design.md §8). sshd is started best-effort:
# a workspace whose sidecars are healthy must still come up when sshd cannot, because the tunnel
# is an operator escape hatch, never a dependency of the product itself.
start_sshd() {
  if [ ! -x /usr/sbin/sshd ]; then
    echo "[dataops-workspace-entrypoint] sshd not present; admin tunnel disabled" >&2
    return 0
  fi
  mkdir -p /run/sshd 2>/dev/null || true
  # Host keys are normally generated by the package; regenerate when an image layer dropped them.
  if [ ! -f /etc/ssh/ssh_host_ed25519_key ]; then
    ssh-keygen -A >/dev/null 2>&1 || true
  fi
  if /usr/sbin/sshd -f /etc/ssh/sshd_config 2>/tmp/sshd-start.log; then
    echo "[dataops-workspace-entrypoint] sshd listening on 0.0.0.0:22 (key-only)"
  else
    echo "[dataops-workspace-entrypoint] sshd failed to start; admin tunnel unavailable (non-fatal): $(cat /tmp/sshd-start.log 2>/dev/null)" >&2
  fi
}

start_sidecars() {
  : >"$SIDECARS_LOG"
  (
    while ! setpriv --reuid=65534 --regid=65534 --clear-groups \
      test -s "$INTERNAL_TOKEN_FILE"; do
      kill -0 "$MAIN_PID" 2>/dev/null || exit 0
      sleep 0.2
    done
    # The sidecars read the owner token from DATAOPS_AI_WORKSPACE_INTERNAL_TOKEN_FILE.
    # The export below is kept for older sidecar builds that only knew the env var; the
    # token file is 0600 and owned by 65534, so the cat must happen after setpriv.
    exec setpriv --reuid=65534 --regid=65534 --clear-groups \
      env DATAOPS_AI_WORKSPACE_INTERNAL_TOKEN_FILE="$INTERNAL_TOKEN_FILE" \
      sh -c '
      export DATAOPS_AI_WORKSPACE_INTERNAL_TOKEN="$(cat "$DATAOPS_AI_WORKSPACE_INTERNAL_TOKEN_FILE")"
      gateway_mode="${DATAOPS_WORKSPACE_GATEWAY_MODE:-combined}"
      echo "[dataops-workspace-entrypoint] gateway mode=${gateway_mode}" >&2
      case "$gateway_mode" in
        combined) exec node /opt/dataops-runtime/src/workspace-gateway.mjs ;;
        split) exec node /opt/dataops-runtime/src/workspace-platform-sidecars.mjs ;;
        *)
          echo "[dataops-workspace-entrypoint] unknown DATAOPS_WORKSPACE_GATEWAY_MODE=${gateway_mode}" >&2
          exit 64
          ;;
      esac'
  ) \
    >"$SIDECARS_LOG" 2>&1 &
  SIDECARS_PID=$!
}

start_sshd

"$@" &
MAIN_PID=$!

if [ -n "${DATAOPS_AI_WORKSPACE_USER_ID:-}" ] \
  && [ -n "${DATAOPS_AI_WORKSPACE_BACKEND_BASE_URL:-}" ]; then
  start_sidecars
fi

while kill -0 "$MAIN_PID" 2>/dev/null; do
  if [ -n "$SIDECARS_PID" ] && ! kill -0 "$SIDECARS_PID" 2>/dev/null; then
    wait "$SIDECARS_PID" 2>/dev/null
    SIDECARS_STATUS=$?
    cat "$SIDECARS_LOG" >&2 2>/dev/null || true
    SIDECARS_PID=''
    if [ "$SIDECARS_STATUS" = 64 ]; then
      echo "[dataops-workspace-entrypoint] unrecoverable gateway mode; stopping workspace" >&2
      stop_child "$MAIN_PID"
      exit 1
    fi
    echo "[dataops-workspace-entrypoint] platform sidecars exited status=$SIDECARS_STATUS; restarting" >&2
    sleep 1
    if kill -0 "$MAIN_PID" 2>/dev/null; then
      start_sidecars
    fi
  fi
  sleep 0.2
done

wait "$MAIN_PID"
MAIN_STATUS=$?
stop_child "$SIDECARS_PID"
exit "$MAIN_STATUS"
