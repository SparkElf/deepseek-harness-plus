export function resolveLocale(preference, browserLanguage = 'zh') {
  if (preference === 'zh' || preference === 'en') return preference
  return browserLanguage.toLowerCase().startsWith('en') ? 'en' : 'zh'
}

export function translate(locale, key, values = {}) {
  const template = localeMessages[locale][key]
  if (template === undefined) throw new Error('missing progress locale key: ' + key)
  return template.replace(/\{\{(\w+)\}\}/gu, (_match, name) => String(values[name] ?? ''))
}
