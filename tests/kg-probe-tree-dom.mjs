import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const ctx = await browser.newContext({ viewport: { width: 1680, height: 1000 }, locale: 'zh-CN' })
const page = await ctx.newPage()
await page.goto('http://127.0.0.1:3000/?test=true', { waitUntil: 'domcontentloaded', timeout: 40000 })
await page.waitForTimeout(10000)
await page.locator('input').nth(0).fill('admin', { force: true })
await page.locator('input[type=password]').fill('DataOps!2026', { force: true })
await page.getByRole('button', { name: '进入工作台', exact: true }).click({ force: true })
await page.waitForTimeout(8000)
await page.goto('http://127.0.0.1:3000/ai/dsh', { waitUntil: 'domcontentloaded', timeout: 40000 })
await page.waitForTimeout(18000)
const frame = page.frames().find(f => f.url().includes(':32000') && !f.url().includes('/knowledge-base/'))
await frame.getByText('知识库', { exact: true }).first().click()
await page.waitForTimeout(1500)
await frame.getByRole('tab', { name: '图谱', exact: true }).click()
await page.waitForTimeout(3000)
const before = await frame.evaluate(() => [...document.querySelectorAll('[data-testid=kg-scope-row]')].map(e => ({ text: (e.textContent||'').trim(), exp: e.getAttribute('aria-expanded'), cls: String(e.className).slice(0,60) })))
console.log('BEFORE', JSON.stringify(before))
const row = frame.locator('[data-testid=kg-scope][data-scope=global] [data-testid=kg-scope-row]').first()
console.log('count', await row.count())
await row.click()
await page.waitForTimeout(800)
const after = await frame.evaluate(() => ({ scopes: [...document.querySelectorAll('[data-testid=kg-scope-row]')].map(e => ({text:(e.textContent||'').trim(), exp:e.getAttribute('aria-expanded')})), graphs: [...document.querySelectorAll('[data-testid=kg-graph]')].map(e => (e.textContent||'').trim()), tree: document.querySelector('[data-testid=kg-tree]')?.innerHTML.slice(0,800) }))
console.log('AFTER', JSON.stringify(after, null, 2))
await page.screenshot({ path: '/root/projects/dsh-ui-shots/kg-tree-dom-probe.png' })
await browser.close()
